def main(out):
    lines = [
        "// GENERATED by tool/theme/make_palette.py. Edit the table there, then regenerate.",
        "import 'package:flutter/material.dart';",
        "",
        "/// One full set of Kalori colour roles (DESIGN.md §2).",
        "class KaloriPalette {",
        "  final Brightness brightness;",
    ]
    for name, _, _, doc in ROLES:
        if doc:
            lines.append(f"  /// {doc}")
        lines.append(f"  final Color {name};")
    lines += ["", "  const KaloriPalette({", "    required this.brightness,"]
    lines += [f"    required this.{n}," for n, *_ in ROLES]
    lines += ["  });", ""]
    for label, idx, bright in (("light", 1, "light"), ("dark", 2, "dark")):
        lines.append(f"  static const KaloriPalette {label} = KaloriPalette(")
        lines.append(f"    brightness: Brightness.{bright},")
        for role in ROLES:
            lines.append(f"    {role[0]}: Color(0x{role[idx]}),")
        lines += ["  );", ""]
    lines += ["  bool get isDark => brightness == Brightness.dark;", "}", ""]

    lines += [
        "/// Colour roles for the active palette.",
        "///",
        "/// Widgets read `KaloriColors.x`; [ThemeService] calls [use] when the app switches",
        "/// between light and dark, then rebuilds the tree so every widget picks up the change.",
        "class KaloriColors {",
        "  KaloriColors._();",
        "",
        "  static KaloriPalette _current = KaloriPalette.light;",
        "",
        "  static KaloriPalette get current => _current;",
        "",
        "  static bool get isDark => _current.isDark;",
        "",
        "  static void use(KaloriPalette palette) => _current = palette;",
        "",
    ]
    for name, *_ in ROLES:
        lines.append(f"  static Color get {name} => _current.{name};")
    lines += ["}", ""]
    lines += [
        "/// Exposes the palette through the theme (`context.colors`), so a widget can also",
        "/// read colours from the [Theme] it is built under.",
        "class KaloriColorExtension extends ThemeExtension<KaloriColorExtension> {",
        "  final KaloriPalette palette;",
        "",
        "  const KaloriColorExtension(this.palette);",
        "",
        "  static const KaloriColorExtension light = KaloriColorExtension(KaloriPalette.light);",
        "  static const KaloriColorExtension dark = KaloriColorExtension(KaloriPalette.dark);",
        "",
        "  @override",
        "  KaloriColorExtension copyWith({KaloriPalette? palette}) => KaloriColorExtension(palette ?? this.palette);",
        "",
        "  @override",
        "  KaloriColorExtension lerp(covariant ThemeExtension<KaloriColorExtension>? other, double t) {",
        "    if (other is! KaloriColorExtension) {",
        "      return this;",
        "    }",
        "    return t < 0.5 ? this : other;",
        "  }",
        "}",
        "",
    ]
    open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print("wrote", out, len(ROLES), "roles")


if __name__ == "__main__":
    main(sys.argv[1])
